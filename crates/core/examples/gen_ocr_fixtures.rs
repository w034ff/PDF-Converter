fn black() -> Result<Fill> {
    Ok(Fill {
        paint: rgb::Color::new(0, 0, 0).into(),
        opacity: NormalizedF32::new(1.0).ok_or("invalid opacity")?,
        rule: FillRule::NonZero,
    })
}

/// The font, for drawing and for looking up glyphs and advances.
struct Typeface<'a> {
    font: Font,
    lookup: skrifa::FontRef<'a>,
}

impl Typeface<'_> {
    /// One glyph per character with its advance; no shaping, which the
    /// pages' Japanese and Latin text does not need.
    fn glyphs(&self, text: &str) -> Vec<KrillaGlyph> {
        let charmap = self.lookup.charmap();
        let metrics = self
            .lookup
            .glyph_metrics(Size::unscaled(), LocationRef::default());
        let units_per_em = self.font.units_per_em();
        text.char_indices()
            .map(|(start, c)| {
                let id = charmap.map(c).unwrap_or_default();
                let advance = metrics.advance_width(id).unwrap_or(0.0) / units_per_em;
                KrillaGlyph::new(
                    GlyphId::new(id.to_u32()),
                    advance,
                    0.0,
                    0.0,
                    0.0,
                    start..start + c.len_utf8(),
                    None,
                )
            })
            .collect()
    }
}

/// Draws `text` left to right with its baseline at `(x, y)` (y downwards).
fn horizontal(
    surface: &mut Surface<'_>,
    font: &Typeface<'_>,
    size: f32,
    x: f32,
    y: f32,
    text: &str,
) {
    surface.draw_glyphs(
        Point::from_xy(x, y),
        &font.glyphs(text),
        font.font.clone(),
        text,
        size,
        false,
    );
}

/// Draws `text` top to bottom, one upright character per `size`, in the
/// column whose left edge is `x` and whose first character's top is `y`.
fn vertical(surface: &mut Surface<'_>, font: &Typeface<'_>, size: f32, x: f32, y: f32, text: &str) {
    for (i, c) in text.chars().enumerate() {
        // The baseline of a full-width character sits about 0.88 em below its top.
        let top = y + i as f32 * size;
        horizontal(surface, font, size, x, top + 0.88 * size, &c.to_string());
    }
}

/// The columns of a tier, right to left from `right_x`, `pitch` apart.
fn tier(
    surface: &mut Surface<'_>,
    font: &Typeface<'_>,
    size: f32,
    right_x: f32,
    top: f32,
    pitch: f32,
    columns: &[&str],
) {
    for (i, column) in columns.iter().enumerate() {
        vertical(surface, font, size, right_x - i as f32 * pitch, top, column);
    }
}

fn page_1(surface: &mut Surface<'_>, font: &Typeface<'_>) {
    horizontal(surface, font, 20.0, 60.0, 100.0, HORIZONTAL_HEADING);
    for (i, line) in HORIZONTAL_BODY.iter().enumerate() {
        horizontal(surface, font, 12.0, 60.0, 160.0 + i as f32 * 20.0, line);
    }
    horizontal(surface, font, 12.0, 60.0, 340.0, HORIZONTAL_LATIN);
}

fn vertical_page(surface: &mut Surface<'_>, font: &Typeface<'_>) {
    vertical(surface, font, 20.0, 500.0, 70.0, VERTICAL_HEADING);
    tier(surface, font, 12.0, 450.0, 70.0, 20.0, &VERTICAL_UPPER);
    tier(surface, font, 12.0, 450.0, 420.0, 20.0, &VERTICAL_LOWER);
}

fn page_3(surface: &mut Surface<'_>, font: &Typeface<'_>) {
    horizontal(surface, font, 18.0, 60.0, 90.0, COLUMNS_HEADING);
    for (i, line) in COLUMNS_LEFT.iter().enumerate() {
        horizontal(surface, font, 12.0, 60.0, 150.0 + i as f32 * 20.0, line);
    }
    for (i, line) in COLUMNS_RIGHT.iter().enumerate() {
        horizontal(surface, font, 12.0, 315.0, 150.0 + i as f32 * 20.0, line);
    }
}

fn page_4(surface: &mut Surface<'_>, font: &Typeface<'_>) {
    horizontal(surface, font, 18.0, 60.0, 90.0, FORM_TITLE);
    for (i, (key, value)) in FORM_ROWS.iter().enumerate() {
        let y = 150.0 + i as f32 * 20.0;
        horizontal(surface, font, 12.0, 80.0, y, key);
        horizontal(surface, font, 12.0, 220.0, y, value);
    }
}

fn page_6(surface: &mut Surface<'_>, font: &Typeface<'_>) {
    for i in 0..60 {
        let line = DENSE_LINES[i % DENSE_LINES.len()];
        horizontal(surface, font, 9.0, 40.0, 50.0 + i as f32 * 12.5, line);
    }
}

/// Page 2 turned by 2° clockwise about the page's centre.
fn page_5(surface: &mut Surface<'_>, font: &Typeface<'_>) {
    let (cx, cy) = (PAGE.0 / 2.0, PAGE.1 / 2.0);
    surface.push_transform(&Transform::from_row(
        COS_2,
        SIN_2,
        -SIN_2,
        COS_2,
        cx - COS_2 * cx + SIN_2 * cy,
        cy - SIN_2 * cx - COS_2 * cy,
    ));
    vertical_page(surface, font);
    surface.pop();
}

/// Draws one page.
type Draw = fn(&mut Surface<'_>, &Typeface<'_>);

fn pages(font: &Typeface<'_>) -> Result<Vec<u8>> {
    let mut document = Document::new();
    let settings = || PageSettings::from_wh(PAGE.0, PAGE.1).ok_or("invalid page size");
    let draws: [Draw; 6] = [page_1, vertical_page, page_3, page_4, page_5, page_6];
    for draw in draws {
        let mut page = document.start_page_with(settings()?);
        let mut surface = page.surface();
        surface.set_fill(Some(black()?));
        draw(&mut surface, font);
        surface.finish();
        page.finish();
    }
    Ok(document.finish()?)
}

fn main() -> Result<()> {
    let font_path = std::env::args_os()
        .nth(1)
        .ok_or("usage: gen_ocr_fixtures <IBMPlexSansJP-Regular.otf>")?;
    let data = std::fs::read(&font_path)?;
    let font = Typeface {
        font: Font::new(data.clone().into(), 0).ok_or("not a font file")?,
        lookup: skrifa::FontRef::new(&data)?,
    };
    let out = Path::new(env!("CARGO_MANIFEST_DIR")).join(OUTPUT);
    if let Some(dir) = out.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&out, pages(&font)?)?;
    println!("wrote {}", out.display());
    Ok(())
}
