//! Generates the OCR test pages of design ocr §11 into
//! `crates/core/tests/ocr-fixtures/ocr_pages.pdf`.
//!
//! Run with the font as its argument and commit the result:
//!
//! ```text
//! cargo run -p pdfconv-core --example gen_ocr_fixtures -- IBMPlexSansJP-Regular.otf
//! ```
//!
//! The font is IBM Plex Sans JP Regular (SIL Open Font License 1.1) from
//! <https://github.com/IBM/plex> at commit
//! bc6a7e4b37634eb79785d59781893db63ee3edcb,
//! `packages/plex-sans-jp/fonts/complete/otf/hinted/IBMPlexSansJP-Regular.otf`,
//! SHA-256 104b96ea945c497a82ff50bc40e52fd2f2c7aa492df08d605a9ab8638375be5e
//! (check it with `sha256sum` before running). It is not committed: the whole file is 4 MB, and a
//! cut-down copy may not keep the name "Plex", which the license reserves. The
//! PDF embeds the subset of the font it uses, which the license allows a
//! document to do. (Drawing the glyphs as outlines instead, as a scan would
//! hold no text, made the file twenty times larger.)
//!
//! Unlike `gen_fixtures`, these pages are not regenerated by the tests, since
//! the tests do not have the font.
//!
//! | Page | Content |
//! | --- | --- |
//! | 1 | Horizontal: a heading, a paragraph and a line of Latin letters and digits |
//! | 2 | Vertical: a heading column on the right, then two tiers of body columns |
//! | 3 | Horizontal in two columns under a heading |
//! | 4 | A form: keys and values side by side |
//! | 5 | Page 2 turned by 2° about its centre |
//! | 6 | A page full of small horizontal text, for the memory test |

use std::error::Error;
use std::path::Path;

use krilla::Document;
use krilla::color::rgb;
use krilla::geom::{Point, Transform};
use krilla::num::NormalizedF32;
use krilla::page::PageSettings;
use krilla::paint::{Fill, FillRule};
use krilla::surface::Surface;
use krilla::text::{Font, GlyphId, KrillaGlyph};
use skrifa::MetadataProvider;
use skrifa::instance::{LocationRef, Size};

type Result<T> = std::result::Result<T, Box<dyn Error>>;

/// Relative to the crate root.
const OUTPUT: &str = "tests/ocr-fixtures/ocr_pages.pdf";

/// A4 in points.
const PAGE: (f32, f32) = (595.28, 841.89);

/// `sin` and `cos` of 2°, written out so that the output does not depend on
/// the platform's trigonometry.
const SIN_2: f32 = 0.034_899_497;
const COS_2: f32 = 0.999_390_8;

